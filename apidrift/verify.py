def verify_source(
    source: str, file_path: str, finding: Finding, vendor: Vendor,
) -> Tuple[str, str, str, List[Site]]:
    """Return (verdict, reason, vendor_evidence, sites) for one file's contents.

    A file is a lead only if dependence can be PROVEN: a call that reaches the
    changed operation by method and path, or a read or write of the changed
    field on a value traced back to the vendor. Everything weaker than that is
    co-location, and co-location produced a nine-in-ten refutation rate across
    two independent audits.
    """
    marker = looks_generated(source)
    if marker:
        return (NOT_AUTHOR_CODE,
                f"header says `{marker}` — generated code is repaired by "
                f"regenerating, not by its authors", "", [])

    licence = looks_vendored_library(source, file_path, vendor)
    if licence:
        return (NOT_AUTHOR_CODE,
                f"`{file_path}` carries a `{licence}` header inside a "
                f"`{vendor.key}` package directory — a checked-in copy of the "
                f"library, not code the repo author wrote", "", [])

    if not file_path.endswith(PY_EXT):
        extension = file_path.rsplit(".", 1)[-1] if "." in file_path else "?"
        return (UNPROVEN,
                f"dependence cannot be established in `.{extension}` — only "
                f"Python is parsed, and an unproven lead is an unmeasured claim",
                "", [])

    evidence = find_vendor_evidence(source, vendor)
    # Required for every kind. Treating a path as self-identifying was wrong:
    # `/v2/conversations` is Twilio's and also gptme's own, and a pytest
    # parametrize list of gptme's routes read as calls to Twilio.
    if not evidence:
        return (NO_VENDOR,
                f"no {vendor.name} import, host or key in the file", "", [])

    proofs, why_not = prove(source, finding, vendor)
    if not proofs:
        return NO_DEPENDENCE, why_not, evidence, []

    sites = [Site(line=p.line, kind=p.kind, text=p.text, chain=p.chain)
             for p in proofs[:5]]
    reason = " — ".join(proofs[0].chain) if proofs[0].chain else proofs[0].kind
    return CONFIRMED, reason, evidence or "path is served only by this vendor", sites


def verify_candidate(
    repo: str, file_path: str, url: str, finding: Finding, vendor: Vendor,
) -> Verdict:
    # Reject on provenance before spending a fetch. The vendor's own SDK, a
    # dataset mirror, a vendored dependency and build output are all incapable
    # of being a customer, whatever their contents say.
    placement = classify(repo, vendor.key, file_path)
    if not placement.is_outreach_target:
        return Verdict(repo=repo, file_path=file_path, url=url,
                       verdict=NOT_AUTHOR_CODE, reason=placement.reason)
    try:
        source, blob_sha = fetch_file(repo, file_path)
    except (FetchError, json.JSONDecodeError, UnicodeDecodeError) as exc:
        return Verdict(repo=repo, file_path=file_path, url=url,
                       verdict=ERROR, reason=str(exc)[:160])
    verdict, reason, evidence, sites = verify_source(source, file_path, finding, vendor)
    return Verdict(repo=repo, file_path=file_path, url=url, verdict=verdict,
                   reason=reason, vendor_evidence=evidence, blob_sha=blob_sha,
                   sites=sites[:5])
