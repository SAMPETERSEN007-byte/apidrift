_IDENT_SPLIT = re.compile(r"[^A-Za-z0-9]+")


def _named_identifier(finding: Finding) -> str:
    """The specific field or schema the change is about, if it names one."""
    subject = finding.root_cause or finding.subject
    leaf = subject.split(".")[-1].replace("[]", "").strip("<>")
    if not leaf or leaf.startswith("<") or len(leaf) < 3:
        return ""
    # Only a name a caller could plausibly write. A status code, a version
    # string or a path fragment is not something to demand appear in the
    # source: a caller of `/bulk-ban` never writes "204".
    # Hyphens are legal in schema names (`Conversation-2`), and skipping them
    # let three test files pass on a `/responses` prefix alone.
    if not leaf[0].isalpha() or not leaf.replace("_", "").replace("-", "").isalnum():
        return ""
    if leaf.lower() in {"id", "type", "name", "url", "data", "status"}:
        return ""
    return leaf


def _identifier_present(source: str, identifier: str) -> bool:
    """Does the identifier occur in the source?

    A PascalCase name is a TYPE name, and generated clients carry it verbatim.
    Matching it case-insensitively is too loose: OpenAI has a schema called
    `Conversation-2`, and `conversation-2` is also an entirely ordinary test
    fixture string. Three leads were three test files using it as sample data.

    A snake_case field name has no such collision problem, and different
    languages case it differently, so those are matched across conventions.
    """
    parts = [p for p in _IDENT_SPLIT.split(identifier) if p]
    if identifier[:1].isupper():
        return identifier in source

    snake = "_".join(p.lower() for p in parts)
    camel = parts[0].lower() + "".join(p.capitalize() for p in parts[1:])
    pascal = "".join(p.capitalize() for p in parts)
    kebab = "-".join(p.lower() for p in parts)
    lowered = source.lower()
    return any(c.lower() in lowered for c in (identifier, snake, camel, pascal, kebab))


def target_symbol(finding: Finding) -> Tuple[str, str]:
    """Return (symbol, mode) describing what to look for in a candidate file."""
    subject = finding.root_cause or finding.subject
    leaf = subject.split(".")[-1].replace("[]", "").strip("<>")
    if finding.kind in _ENDPOINT_KINDS:
        # The same rule prospecting uses. Truncating at the first parameter
        # left `/guilds` standing for `/guilds/{guild_id}/bulk-ban`, so a
        # removed 204 on bulk-ban "matched" a GET of /users/@me/guilds.
        return static_run(finding.path), "endpoint"
    if finding.kind in _ABSENCE_KINDS:
        return leaf, "absence"
    if finding.kind in _FIELD_KINDS:
        return leaf, "presence"
    return leaf, "presence"


